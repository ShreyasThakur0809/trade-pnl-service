"""The committed sample dataset must exercise the service's edge cases.

data/sample_trades.json is generated by scripts/seed.py and is part of the
deliverable — this test keeps it honest by running every batch through the
real ingestion path.
"""
from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path

import pytest

DATA = json.loads((Path(__file__).parents[1] / "data" / "sample_trades.json").read_text())


@pytest.fixture
def seeded(client):
    totals = {"accepted": 0, "duplicates": 0, "rejected": 0}
    for batch in DATA["batches"]:
        r = client.post(batch["endpoint"], json=batch["payload"])
        assert r.status_code == 200, r.text
        res = r.json()
        for k in totals:
            totals[k] += res[k]
    return totals


def test_dataset_ingests_with_expected_edge_cases(client, seeded):
    assert seeded["accepted"] >= 20          # all real fills applied
    assert seeded["duplicates"] == 1         # the replayed binance fill
    assert seeded["rejected"] == 1           # the planted oversell

    item = next(
        r for b in DATA["batches"] if b["endpoint"] == "/v1/trades"
        for r in [client.post(b["endpoint"], json=b["payload"]).json()["results"][0]]
        if r["status"] == "rejected"
    )
    assert item["code"] == "OVERSELL"


def test_dataset_positions_exist(client, seeded):
    positions = client.get("/v1/positions").json()
    venues = {p["venue"] for p in positions}
    assert {"binance", "coinbase", "coindcx", "kraken"} <= venues


def test_dataset_reconcile_finds_planted_break(client, seeded):
    r = client.post("/v1/reconcile", json=DATA["reconcile"])
    report = r.json()
    assert report["breaks"] == 1
    row = next(r for r in report["results"] if r["status"] == "break")
    assert Decimal(row["diff"]) == Decimal("0.02")


def test_dataset_marks_feed_pnl(client, seeded):
    client.post("/v1/marks", json={"marks": DATA["marks"]})
    report = client.get("/v1/pnl").json()
    assert report["positions"]
    assert all(p["mark_price"] is not None for p in report["positions"])
